/// Parse a whole `<function_calls>` body: one call per line.
///
/// **Upstream:** `parseOlmo3FunctionCalls`. Blank lines are skipped; a body that
/// is entirely whitespace yields no calls and no error.
///
/// **Newlines are the separator, full stop.** A single call may therefore not
/// span lines -- upstream splits on `\n` before parsing, so a pretty-printed
/// multi-line dict argument would break. That is a real limitation of the
/// format, not of this port.
fn parse_function_calls(s: &str) -> Result<Vec<ToolCall>, ParserError> {
    let mut calls = Vec::new();
    let s = s.trim();
    if s.is_empty() {
        return Ok(calls);
    }

    for line in s.split('\n') {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        calls.push(parse_single_function_call(line)?);
    }

    Ok(calls)
}

/// Parse one `name(args)` line.
///
/// **Upstream:** `parseOlmo3SingleFunctionCall` plus its
/// `regexp.MustCompile(`^(\w+)\((.*)\)$`)`.
///
/// Hand-rolled rather than pulling in `regex`, and it is **exactly** equivalent
/// for this pattern, not an approximation:
///
/// * the whole line must end in `)` (the regex is anchored `$`);
/// * `\w+` cannot contain `(`, so the **first** `(` is where the name ends;
/// * `(.*)` is greedy and `$`-anchored, so the arguments run to the **last**
///   `)`, which is what makes a nested call like `f(g(x))` come out as name `f`,
///   args `g(x)`;
/// * `\w` in Go's RE2 is `[0-9A-Za-z_]` -- ASCII only. So a Unicode function
///   name does **not** match and is rejected, same as upstream.
fn parse_single_function_call(s: &str) -> Result<ToolCall, ParserError> {
    let invalid = || ParserError::MalformedToolCall(format!("invalid function call format: {s}"));

    let rest = s.strip_suffix(')').ok_or_else(invalid)?;
    let open = rest.find('(').ok_or_else(invalid)?;
    let (func_name, args_str) = (&rest[..open], &rest[open + 1..]);

    if func_name.is_empty() || !func_name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
        return Err(invalid());
    }

    Ok(ToolCall {
        function: ToolCallFunction {
            name: func_name.to_string(),
            arguments: parse_arguments(args_str)?,
            ..Default::default()
        },
        ..Default::default()
    })
}

/// Parse `key=value, key=value` into ordered arguments.
///
/// **Upstream:** `parseOlmo3Arguments`. Splits on the **first** `=` in each
/// part, so `expr="a=b"` keeps `a=b` as the value.
fn parse_arguments(s: &str) -> Result<ToolCallArguments, ParserError> {
    let mut args = ToolCallArguments::new();
    let s = s.trim();
    if s.is_empty() {
        return Ok(args);
    }

    for part in split_arguments(s) {
        let part = part.trim();
        if part.is_empty() {
            continue;
        }
        let eq = part
            .find('=')
            .ok_or_else(|| ParserError::MalformedToolCall(format!("invalid argument format: {part}")))?;
        let key = part[..eq].trim();
        let value_str = part[eq + 1..].trim();
        args.set(key, parse_value(value_str));
    }

    Ok(args)
}

/// Split on commas that are **not** inside quotes or nested brackets.
///
/// **Upstream:** `splitArguments`. This is why `f(items=["a,b"], n=1)` splits
/// into two parts and not three -- a naive `split(',')` mangles every list and
/// every string containing a comma.
///
/// **Divergence, and why it is safe:** upstream walks raw *bytes*; we walk
/// `char`s. Every character it treats specially (`\`, `"`, `'`, brackets, comma)
/// is ASCII, and a UTF-8 continuation byte can never equal an ASCII byte, so a
/// multi-byte character always lands in the same `default` branch either way.
/// Identical output, minus the risk of slicing mid-character.
///
/// The escape handling is upstream's exactly: a backslash only escapes **inside
/// a string**, and the backslash itself is kept in the output for
/// [`unescape_string`] to deal with later.
fn split_arguments(s: &str) -> Vec<String> {
    let mut parts = Vec::new();
    let mut current = String::new();
    let mut depth: i32 = 0;
    let mut in_string = false;
    let mut string_char = '\0';
    let mut escaped = false;

    for c in s.chars() {
        if escaped {
            current.push(c);
            escaped = false;
            continue;
        }

        if c == '\\' && in_string {
            current.push(c);
            escaped = true;
            continue;
        }

        if (c == '"' || c == '\'') && !in_string {
            in_string = true;
            string_char = c;
            current.push(c);
            continue;
        }

        if c == string_char && in_string {
            in_string = false;
            string_char = '\0';
            current.push(c);
            continue;
        }

        if !in_string {
            match c {
                '(' | '[' | '{' => {
                    depth += 1;
                    current.push(c);
                }
                ')' | ']' | '}' => {
                    depth -= 1;
                    current.push(c);
                }
                ',' if depth == 0 => {
                    parts.push(std::mem::take(&mut current));
                }
                _ => current.push(c),
            }
        } else {
            current.push(c);
        }
    }

    if !current.is_empty() {
        parts.push(current);
    }

    parts
}

/// Parse one Python-ish literal.
///
/// **Upstream:** `parseOlmo3Value`. The order of the checks is load-bearing and
/// is upstream's:
///
/// 1. quoted string (either quote style) -- checked first so `"123"` stays the
///    **string** `"123"` and does not become the number `123`;
/// 2. `true`/`True`, `false`/`False` -- both casings, because the model may emit
///    Python or JSON spelling;
/// 3. `null`/`None`/`nil`;
/// 4. integer, then float -- integer first so `72` is an integer and not `72.0`;
/// 5. `[...]` list, `{...}` dict;
/// 6. **anything else falls back to a bare string**, unquoted. So a stray
///    `location=SF` yields `"SF"` rather than an error. Lenient on purpose:
///    upstream would rather make the call than drop it.
///
/// **Never returns an error** -- upstream's signature has one but no branch ever
/// populates it (the recursive list/dict cases only forward their own, which are
/// likewise unreachable). Dropped rather than ported as an `Err` that cannot
/// happen.
///
/// A dict's keys land in a `serde_json::Map`. Upstream uses Go's `map[string]any`,
/// which has **no** order at all, so nothing observable is lost -- unlike the
/// top-level [`ToolCallArguments`], where insertion order genuinely matters.
fn parse_value(s: &str) -> serde_json::Value {
    use serde_json::Value;

    let s = s.trim();

    // Quoted string. Note `len() >= 2` guards the degenerate `"` (one byte),
    // which would otherwise both start and end the string.
    if s.len() >= 2
        && ((s.starts_with('"') && s.ends_with('"')) || (s.starts_with('\'') && s.ends_with('\'')))
    {
        return Value::String(unescape_string(&s[1..s.len() - 1]));
    }

    if s == "true" || s == "True" {
        return Value::Bool(true);
    }
    if s == "false" || s == "False" {
        return Value::Bool(false);
    }
    if s == "null" || s == "None" || s == "nil" {
        return Value::Null;
    }

    if let Ok(i) = s.parse::<i64>() {
        return Value::Number(i.into());
    }
    if let Ok(f) = s.parse::<f64>()
        && let Some(n) = serde_json::Number::from_f64(f)
    {
        return Value::Number(n);
    }

    if let Some(inner) = s.strip_prefix('[').and_then(|x| x.strip_suffix(']')) {
        let inner = inner.trim();
        if inner.is_empty() {
            return Value::Array(Vec::new());
        }
        return Value::Array(split_arguments(inner).iter().map(|p| parse_value(p)).collect());
    }

    if let Some(inner) = s.strip_prefix('{').and_then(|x| x.strip_suffix('}')) {
        return parse_object(inner);
    }

    // Bare, unquoted -- keep it as a string.
    Value::String(s.to_string())
}

/// Parse a `{...}` body: `key: value` pairs, keys optionally quoted.
///
/// **Upstream:** `parseOlmo3Object`. Note the separator is `:` (dict syntax),
/// not `=` (call syntax) -- mixing the two up is the easy mistake here.
///
/// A malformed entry (no `:`) is **skipped**, where upstream returns an error
/// that its only caller then swallows into a bare-string fallback. Same
/// observable result for the entry, and it keeps the sibling keys that did
/// parse. Stated because it is a divergence in the code shape, not the outcome.
fn parse_object(s: &str) -> serde_json::Value {
    let s = s.trim();
    let mut obj = serde_json::Map::new();
    if s.is_empty() {
        return serde_json::Value::Object(obj);
    }

    for part in split_arguments(s) {
        let part = part.trim();
        if part.is_empty() {
            continue;
        }
        let Some(colon) = part.find(':') else {
            continue;
        };
        let mut key = part[..colon].trim();
        let value_str = part[colon + 1..].trim();

        if key.len() >= 2
            && ((key.starts_with('"') && key.ends_with('"'))
                || (key.starts_with('\'') && key.ends_with('\'')))
        {
            key = &key[1..key.len() - 1];
        }

        obj.insert(key.to_string(), parse_value(value_str));
    }

    serde_json::Value::Object(obj)
}

/// Undo the escapes olmo 3 uses inside a quoted argument.
///
/// **Upstream:** `unescapeString`, including its **NUL-placeholder trick**:
/// `\\` is first swapped for a literal `\0`, the other escapes are then
/// expanded, and finally `\0` becomes a single backslash.
///
/// The trick is not decoration -- it is what stops `\\n` (an escaped backslash
/// followed by the letter `n`) from being mangled into a newline. Rewrite this
/// as five independent `replace` calls and that case silently breaks.
///
/// **What would make this wrong:** an argument that genuinely contains a NUL
/// byte would be corrupted, since the placeholder collides with it. That is
/// upstream's bug and it is carried faithfully; a tool argument containing a raw
/// NUL is not a thing any model emits, and diverging here would mean this port
/// and ollama disagree on a real input.
fn unescape_string(s: &str) -> String {
    const PLACEHOLDER: &str = "\u{0}";
    let s = s.replace("\\\\", PLACEHOLDER);
    let s = s.replace("\\\"", "\"");
    let s = s.replace("\\'", "'");
    let s = s.replace("\\n", "\n");
    let s = s.replace("\\t", "\t");
    let s = s.replace("\\r", "\r");
    s.replace(PLACEHOLDER, "\\")
}

