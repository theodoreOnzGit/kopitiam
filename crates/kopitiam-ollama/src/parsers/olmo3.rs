/// **Upstream:** `olmo3ThinkParserState`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
enum ThinkState {
    #[default]
    CollectingThink,
    CollectingContent,
}

/// The `olmo3-think` parser. **Upstream:** `Olmo3ThinkParser`.
///
/// No tool support at all -- [`has_tool_support`](Parser::has_tool_support) is
/// `false`, so a `<function_calls>` block from this model would come out as
/// plain content. That is upstream's shape, not an omission in this port.
#[derive(Debug, Default)]
pub struct Olmo3ThinkParser {
    state: ThinkState,
    buffer: String,
}

impl Olmo3ThinkParser {
    /// **Upstream:** `setInitialState`.
    ///
    /// The model **always thinks first**, because the prompt template injects
    /// the opening `<think>` itself. The single exception is an assistant
    /// prefill *with content*: the caller already started the visible reply, so
    /// thinking is over before generation begins.
    ///
    /// Note it checks `Role == "assistant"` and `Content != ""` -- a prefill
    /// carrying only `thinking` still starts in thinking mode, which is right:
    /// the model is continuing that thought.
    fn set_initial_state(&mut self, last_message: Option<&Message>) {
        let prefill = last_message.is_some_and(|m| m.role == "assistant");
        if prefill && last_message.is_some_and(|m| !m.content.is_empty()) {
            self.state = ThinkState::CollectingContent;
            return;
        }
        self.state = ThinkState::CollectingThink;
    }

    /// **Upstream:** `(*Olmo3ThinkParser).parseEvents`.
    fn parse_events(&mut self) -> Vec<ThinkEvent> {
        let mut all = Vec::new();
        let mut keep_looping = true;
        while keep_looping {
            let (events, again) = self.eat();
            keep_looping = again;
            all.extend(events);
        }
        all
    }

    /// **Upstream:** `(*Olmo3ThinkParser).eat`.
    fn eat(&mut self) -> (Vec<ThinkEvent>, bool) {
        if self.buffer.is_empty() {
            return (Vec::new(), false);
        }

        match self.state {
            ThinkState::CollectingThink => {
                if let Some(idx) = self.buffer.find(THINK_CLOSE_TAG) {
                    let thinking = self.buffer[..idx].trim_end().to_string();
                    let remaining = self.buffer[idx + THINK_CLOSE_TAG.len()..]
                        .trim_start()
                        .to_string();
                    self.buffer = remaining;
                    self.state = ThinkState::CollectingContent;
                    let mut events = Vec::new();
                    if !thinking.is_empty() {
                        events.push(ThinkEvent::Thinking(thinking));
                    }
                    return (events, true);
                }

                // Unlike `Olmo3Parser` above, this one DOES widen the held-back
                // region over trailing whitespace -- because `</think>` is
                // framing and the whitespace in front of it gets trimmed if the
                // tag arrives. Emit that whitespace early and you can never take
                // it back. Same shape as `emit_unambiguous`, spelled out because
                // the two olmo3 parsers deliberately differ here.
                let overlap_len = overlap(&self.buffer, THINK_CLOSE_TAG);
                let split = self.buffer.len() - overlap_len;
                let (before_partial_tag, _) = super::chop(&self.buffer, split);
                let ambiguous_start =
                    before_partial_tag.len() - trailing_whitespace_len(before_partial_tag);
                let (unambiguous, ambiguous) = super::chop(&self.buffer, ambiguous_start);
                let (unambiguous, ambiguous) = (unambiguous.to_string(), ambiguous.to_string());
                self.buffer = ambiguous;
                let mut events = Vec::new();
                if !unambiguous.is_empty() {
                    events.push(ThinkEvent::Thinking(unambiguous));
                }
                (events, false)
            }

            ThinkState::CollectingContent => {
                let content = std::mem::take(&mut self.buffer);
                (vec![ThinkEvent::Content(content)], false)
            }
        }
    }
}

/// **Upstream:** `olmo3Event`.
#[derive(Debug, Clone, PartialEq)]
enum ThinkEvent {
    Thinking(String),
    Content(String),
}

impl Parser for Olmo3ThinkParser {
    fn init(
        &mut self,
        tools: Vec<Tool>,
        last_message: Option<&Message>,
        _think: Option<&ThinkValue>,
    ) -> Vec<Tool> {
        self.set_initial_state(last_message);
        self.buffer.clear();
        tools
    }

    /// **Upstream:** `(*Olmo3ThinkParser).Add`. Note `done` is **ignored** here
    /// -- there is nothing that only drains at the end, because every state
    /// already emits whatever it can on every call. The only thing ever held
    /// back is an ambiguous partial `</think>`, and a stream that ends mid-tag
    /// never had a closing tag to honour anyway.
    fn add(&mut self, s: &str, _done: bool) -> Result<Parsed, ParserError> {
        self.buffer.push_str(s);
        let mut out = Parsed::default();
        for event in self.parse_events() {
            match event {
                ThinkEvent::Thinking(t) => out.thinking.push_str(&t),
                ThinkEvent::Content(c) => out.content.push_str(&c),
            }
        }
        Ok(out)
    }

    fn preserved_tokens(&self) -> Vec<&'static str> {
        vec![THINK_CLOSE_TAG]
    }

    fn has_tool_support(&self) -> bool {
        false
    }

    fn has_thinking_support(&self) -> bool {
        true
    }
}

