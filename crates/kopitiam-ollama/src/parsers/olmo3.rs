    /// Upstream `TestOlmo3Parser_Streaming`.
    #[test]
    fn olmo3_survives_the_open_tag_being_split_across_chunks() {
        let cases: Vec<(Vec<&str>, &str, usize)> = vec![
            (vec!["Hello, ", "how ", "can I help?"], "Hello, how can I help?", 0),
            (
                vec!["<function_", "calls>get_weather", "(location=\"SF\")", "</function_calls>"],
                "",
                1,
            ),
            (
                vec!["Let me check.", "<function_calls>", "get_weather(location=\"NYC\")", "</function_calls>"],
                "Let me check.",
                1,
            ),
            (vec!["<func", "tion_calls>test()</function_calls>"], "", 1),
        ];

        for (chunks, want_content, want_calls) in cases {
            let mut p = olmo3();
            let mut content = String::new();
            let mut calls = Vec::new();
            for chunk in &chunks {
                let got = p.add(chunk, false).expect("add");
                content.push_str(&got.content);
                calls.extend(got.calls);
            }
            let got = p.add("", true).expect("drain");
            content.push_str(&got.content);
            calls.extend(got.calls);

            assert_eq!(content, want_content, "for {chunks:?}");
            assert_eq!(calls.len(), want_calls, "for {chunks:?}");
        }
    }

    /// One byte at a time must agree with one big chunk.
    #[test]
    fn olmo3_fed_one_byte_at_a_time_gives_the_same_answer() {
        let input = "Checking now.<function_calls>get_weather(location=\"SG\")</function_calls>All done.";

        let mut whole = olmo3();
        let want = run(&mut whole, input);

        let mut p = olmo3();
        let mut got = Parsed::default();
        for (i, ch) in input.char_indices() {
            let part = p.add(&input[i..i + ch.len_utf8()], false).expect("add");
            got.content.push_str(&part.content);
            got.calls.extend(part.calls);
        }
        let drained = p.add("", true).expect("drain");
        got.content.push_str(&drained.content);
        got.calls.extend(drained.calls);

        assert_eq!(got.content, want.content);
        assert_eq!(got.content, "Checking now.All done.");
        assert_eq!(got.calls.len(), want.calls.len());
        assert_eq!(got.calls.len(), 1);
    }

