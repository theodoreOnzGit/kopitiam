    #[test]
    fn olmo3_think_fed_one_byte_at_a_time_gives_the_same_answer() {
        let input = "let me work it out</think>The answer is 4.";

        let mut whole = olmo3_think();
        let want = whole.add(input, true).expect("add");

        let mut p = olmo3_think();
        let mut got = Parsed::default();
        for (i, ch) in input.char_indices() {
            let part = p
                .add(&input[i..i + ch.len_utf8()], i + ch.len_utf8() == input.len())
                .expect("add");
            got.content.push_str(&part.content);
            got.thinking.push_str(&part.thinking);
        }

        assert_eq!(got.thinking, want.thinking);
        assert_eq!(got.content, want.content);
        assert_eq!(got.thinking, "let me work it out");
        assert_eq!(got.content, "The answer is 4.");
    }

