//! Olmo 3 -- two parsers, one family.
//!
//! **Upstream:** `model/parsers/olmo3.go` and `model/parsers/olmo3_think.go`
//! (ollama, MIT, Copyright (c) Ollama). Ported against
//! `4713800b08b2ddf5e14acf8398953cf7b12f169b` (2026-07-28).
//!
//! | parser name | struct | tools | thinking |
//! |---|---|---|---|
//! | `olmo3` | [`Olmo3Parser`] | yes | no |
//! | `olmo3-think` | [`Olmo3ThinkParser`] | no | yes |
//!
//! They are genuinely separate upstream -- not one struct with flags -- because
//! they share no state machine at all. Kept separate here for the same reason.
//!
//! ## Olmo 3 calls tools in Python, not JSON
//!
//! This is the interesting bit and the reason this file is long:
//!
//! ```text
//! <function_calls>get_weather(location="San Francisco", units='metric')
//! get_time(timezone="PST")</function_calls>
//! ```
//!
//! One call per line, Python call syntax, Python literals -- `True`/`true`,
//! `None`/`null`/`nil`, single **or** double quotes, `[...]` lists and `{...}`
//! dicts. So there is a small recursive-descent literal parser at the bottom of
//! this file. It is upstream's, warts included.
//!
//! **What would make this wrong:** reaching for `serde_json` on that body. It is
//! *not* JSON -- `location="SF"` uses `=` not `:`, `True` is capitalised, keys
//! are bare, and strings may be single-quoted. Feeding it to a JSON parser fails
//! on every single real tool call.
//!
//! ## The `done` contract here is unusual, hor -- read this before using it
//!
//! [`Olmo3Parser::add`] with `done = true` **does not parse anything**. It
//! drains the buffer and returns it as content (only if it is still in the
//! content state), and that is all -- upstream returns before `parseEvents` is
//! ever reached.
//!
//! So the caller MUST feed real chunks with `done = false` and use the final
//! `add("", true)` purely as a drain. Handing the whole response in one
//! `add(everything, true)` returns the raw string, `<function_calls>` markup and
//! all, and finds zero tool calls. Upstream's own tests are written exactly that
//! way (`Add(input, false)` then `Add("", true)`), which is how we know it is
//! intended and not an accident.

use crate::api::{Message, ThinkValue, Tool, ToolCall, ToolCallArguments, ToolCallFunction};

use super::{Parsed, Parser, ParserError, overlap, trailing_whitespace_len};

/// **Upstream:** `olmo3FuncCallsOpenTag` / `olmo3FuncCallsCloseTag`.
const FUNC_CALLS_OPEN_TAG: &str = "<function_calls>";
const FUNC_CALLS_CLOSE_TAG: &str = "</function_calls>";

/// **Upstream:** `olmo3ThinkCloseTag`. Note there is no *open* tag: the prompt
/// injects `<think>` itself, so the model's very first generated byte is already
/// inside the thinking block.
const THINK_CLOSE_TAG: &str = "</think>";

// ===========================================================================
// olmo3 -- tool calls, no thinking.
// ===========================================================================

/// **Upstream:** `olmo3ParserState`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
enum State {
    #[default]
    Content,
    ToolCalls,
    /// One-shot state right after `</function_calls>`: dump whatever trails and
    /// go back to [`State::Content`]. Upstream keeps it as its own state rather
    /// than falling straight back, and the difference is observable -- the
    /// trailing text is emitted **without** any partial-open-tag buffering on
    /// that one pass.
    ToolCallsDone,
}

/// **Upstream:** `olmo3ParserEvent`.
#[derive(Debug, Clone, PartialEq)]
enum Event {
    Content(String),
    ToolCalls(Vec<ToolCall>),
}

/// The `olmo3` parser. **Upstream:** `Olmo3Parser`.
#[derive(Debug, Default)]
pub struct Olmo3Parser {
    state: State,
    buffer: String,
    /// Running counter across the whole generation, so parallel calls come back
    /// numbered 0, 1, 2, ... **Upstream:** `callIndex`. It is a *stream*
    /// counter, not a per-chunk one -- resetting it per chunk would make two
    /// calls in two chunks both claim index 0.
    call_index: usize,
}

impl Olmo3Parser {
    /// **Upstream:** `(*Olmo3Parser).parseEvents`.
    fn parse_events(&mut self) -> Vec<Event> {
        let mut all = Vec::new();
        let mut keep_looping = true;
        while keep_looping {
            let (events, again) = self.eat();
            keep_looping = again;
            all.extend(events);
        }
        all
    }

    /// **Upstream:** `(*Olmo3Parser).eat`.
    fn eat(&mut self) -> (Vec<Event>, bool) {
        if self.buffer.is_empty() {
            return (Vec::new(), false);
        }

        match self.state {
            State::Content => {
                if let Some(idx) = self.buffer.find(FUNC_CALLS_OPEN_TAG) {
                    let content = self.buffer[..idx].to_string();
                    let remaining = self.buffer[idx + FUNC_CALLS_OPEN_TAG.len()..].to_string();
                    self.buffer = remaining;
                    self.state = State::ToolCalls;
                    let mut events = Vec::new();
                    if !content.is_empty() {
                        events.push(Event::Content(content));
                    }
                    return (events, true);
                }

                let overlap_len = overlap(&self.buffer, FUNC_CALLS_OPEN_TAG);
                if overlap_len > 0 {
                    // Hold back exactly the ambiguous tail, emit the rest.
                    //
                    // NOTE, and this is a real difference from the qwen
                    // families: upstream does **not** widen the held-back
                    // region over trailing whitespace here, so we must not call
                    // `emit_unambiguous` (which does). Olmo 3 puts
                    // `<function_calls>` straight after prose with no framing
                    // whitespace convention, so the space in front of it is the
                    // user's content and eating it would be a visible bug.
                    let split = self.buffer.len() - overlap_len;
                    let (unambiguous, ambiguous) = super::chop(&self.buffer, split);
                    let (unambiguous, ambiguous) = (unambiguous.to_string(), ambiguous.to_string());
                    self.buffer = ambiguous;
                    let mut events = Vec::new();
                    if !unambiguous.is_empty() {
                        events.push(Event::Content(unambiguous));
                    }
                    return (events, false);
                }

                // Nothing tag-shaped in sight: all of it is content.
                let content = std::mem::take(&mut self.buffer);
                (vec![Event::Content(content)], false)
            }

            State::ToolCalls => {
                let Some(idx) = self.buffer.find(FUNC_CALLS_CLOSE_TAG) else {
                    // Still collecting the body. Nothing can be emitted early --
                    // a half-written `get_weather(location="S` is not a call yet.
                    return (Vec::new(), false);
                };
                let tool_calls_str = self.buffer[..idx].to_string();
                let remaining = self.buffer[idx + FUNC_CALLS_CLOSE_TAG.len()..].to_string();
                self.buffer = remaining;
                self.state = State::ToolCallsDone;

                // **Upstream swallows the error here** (it only trace-logs), so
                // a malformed body yields no calls rather than failing the
                // generation. Kept: olmo3 emits several calls in one block, and
                // upstream's judgment is that losing the block beats killing a
                // reply that may already have useful content in it.
                match parse_function_calls(&tool_calls_str) {
                    Ok(calls) if !calls.is_empty() => (vec![Event::ToolCalls(calls)], true),
                    _ => (Vec::new(), true),
                }
            }

            State::ToolCallsDone => {
                let content = std::mem::take(&mut self.buffer);
                self.state = State::Content;
                if content.is_empty() {
                    return (Vec::new(), false);
                }
                (vec![Event::Content(content)], false)
            }
        }
    }
}

impl Parser for Olmo3Parser {
    /// **Upstream:** `(*Olmo3Parser).Init`. Tools pass straight through -- olmo3
    /// does not rename anything.
    fn init(
        &mut self,
        tools: Vec<Tool>,
        _last_message: Option<&Message>,
        _think: Option<&ThinkValue>,
    ) -> Vec<Tool> {
        self.state = State::Content;
        self.call_index = 0;
        // Upstream does not clear the buffer in Init. We do, because a stale
        // buffer with a fresh state is a bug waiting to happen and upstream only
        // gets away with it by always constructing a fresh parser. Stated as a
        // divergence; it cannot change behaviour for any caller that follows the
        // documented init-then-add lifecycle.
        self.buffer.clear();
        tools
    }

    /// **Upstream:** `(*Olmo3Parser).Add`. See the module docs -- the `done`
    /// branch returns **before** any parsing happens, so it is a drain only.
    fn add(&mut self, s: &str, done: bool) -> Result<Parsed, ParserError> {
        self.buffer.push_str(s);

        if done {
            let buf = std::mem::take(&mut self.buffer);
            if self.state == State::Content && !buf.is_empty() {
                return Ok(Parsed {
                    content: buf,
                    ..Default::default()
                });
            }
            // Mid-tool-call at `done` means the model stopped before closing
            // `</function_calls>`. The half-written body is dropped, not
            // guessed at. Upstream does the same.
            return Ok(Parsed::default());
        }

        let mut out = Parsed::default();
        for event in self.parse_events() {
            match event {
                Event::Content(c) => out.content.push_str(&c),
                Event::ToolCalls(calls) => out.calls.extend(calls),
            }
        }

        for call in &mut out.calls {
            call.function.index = self.call_index;
            self.call_index += 1;
        }

        Ok(out)
    }

    fn preserved_tokens(&self) -> Vec<&'static str> {
        vec![FUNC_CALLS_OPEN_TAG, FUNC_CALLS_CLOSE_TAG]
    }

    fn has_tool_support(&self) -> bool {
        true
    }

    fn has_thinking_support(&self) -> bool {
        false
    }
}

