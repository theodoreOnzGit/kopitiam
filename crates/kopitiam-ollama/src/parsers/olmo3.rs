    /// Upstream's own harness: feed the body with `done = false`, then drain
    /// with `add("", true)`. See the module docs for why that order is required.
    fn run(p: &mut Olmo3Parser, input: &str) -> Parsed {
        let mut got = p.add(input, false).expect("add");
        let drained = p.add("", true).expect("drain");
        got.content.push_str(&drained.content);
        got.thinking.push_str(&drained.thinking);
        got.calls.extend(drained.calls);
        got
    }

    /// Upstream `TestOlmo3Parser`, ported verbatim as ground truth.
    #[test]
    fn olmo3_splits_content_from_python_style_tool_calls() {
        let mut p = olmo3();
        let got = run(&mut p, "Hello, how can I help you?");
        assert_eq!(got.content, "Hello, how can I help you?");
        assert!(got.calls.is_empty());

        let mut p = olmo3();
        let got = run(
            &mut p,
            r#"<function_calls>get_weather(location="San Francisco")</function_calls>"#,
        );
        assert!(got.content.is_empty());
        assert_eq!(got.calls.len(), 1);
        assert_eq!(got.calls[0].function.name, "get_weather");
        assert_eq!(
            got.calls[0].function.arguments.get("location"),
            Some(&json!("San Francisco"))
        );

        let mut p = olmo3();
        let got = run(
            &mut p,
            r#"Let me check the weather.<function_calls>get_weather(location="NYC")</function_calls>"#,
        );
        assert_eq!(got.content, "Let me check the weather.");
        assert_eq!(got.calls.len(), 1);
    }

