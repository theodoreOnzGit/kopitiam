//! Decode tables for [`super::filter_fax`], ported verbatim from MuPDF
//! `source/fitz/filter-fax.c` (commit 1ca9d1788, AGPL-3.0, © Artifex
//! Software, Inc.), translated to Rust for KOPITIAM (AGPL-3.0-only).
//!
//! "Verbatim" is meant literally: every entry is the upstream value at the
//! upstream index. There is no adaptation here to get wrong.
//!
//! **Generated, not typed.** These three tables are 776 entries between them
//! and a single transposed digit would corrupt one run length in one colour
//! at one bit width -- a fault that shows up as a few wrong pixels on some
//! scans and nowhere else. They were extracted from the C source by script;
//! do not hand-edit. Re-extract if MuPDF's tables ever change.
//!
//! The layout is MuPDF's two-level scheme, described in its own header: the
//! first `initial_bits` of the code index the table directly; an entry whose
//! `nbits` exceeds `initial_bits` is a pointer to a mini-table whose size is
//! `2^(nbits - initial_bits)`.

/// One decode-table entry: `val` is a run length or a negative semantic code,
/// `nbits` the code width (or, for a first-level pointer, the maximum width
/// of all codes sharing that prefix).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) struct CfdNode {
    pub(super) val: i16,
    pub(super) nbits: i16,
}

const fn n(val: i16, nbits: i16) -> CfdNode {
    CfdNode { val, nbits }
}

